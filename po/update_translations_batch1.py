def update_po(lang, translations):
    filename = f"{lang}.po"
    if not os.path.exists(filename):
        print(f"Skipping {filename}: Not found")
        return
    
    with open(filename, 'r') as f:
        content = f.read()
    
    for msgid, msgstr in translations.items():
        # Replace empty msgstr for specific msgid
        pattern = re.compile(r'(msgid "' + re.escape(msgid) + r'")\nmsgstr ""')
        replacement = r'\1\nmsgstr "' + msgstr + r'"'
        content = pattern.sub(replacement, content)
        
        # Also replace fuzzy ones if necessary, but start with empty ones
    
    with open(filename, 'w') as f:
        f.write(content)
    print(f"Updated {filename}")

for lang, trans_dict in translations.items():
    update_po(lang, trans_dict)
